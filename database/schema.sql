CREATE DATABASE IF NOT EXISTS db_actrace CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE db_actrace;
CREATE TABLE IF NOT EXISTS users (
 user_id INT AUTO_INCREMENT PRIMARY KEY,
 student_code VARCHAR(30) NOT NULL UNIQUE,
 full_name VARCHAR(100) NOT NULL,
 username VARCHAR(50) NOT NULL UNIQUE,
 email VARCHAR(100) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 photo VARCHAR(255) DEFAULT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS journals (
 journal_id INT AUTO_INCREMENT PRIMARY KEY,
 user_id INT NOT NULL,
 activity_date DATE NOT NULL,
 title VARCHAR(150) NOT NULL,
 description TEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_journals_users FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE ON UPDATE CASCADE,
 INDEX idx_journals_user_date (user_id, activity_date)
);
CREATE TABLE IF NOT EXISTS journal_photos (
 photo_id INT AUTO_INCREMENT PRIMARY KEY,
 journal_id INT NOT NULL,
 file_name VARCHAR(255) NOT NULL,
 file_path VARCHAR(255) NOT NULL,
 uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_photos_journals FOREIGN KEY (journal_id) REFERENCES journals(journal_id) ON DELETE CASCADE ON UPDATE CASCADE
);